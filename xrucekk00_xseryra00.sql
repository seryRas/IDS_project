CREATE TABLE Products (
    product_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name VARCHAR2(255) NOT NULL,
    product_description VARCHAR2(1024),
    price NUMBER(8, 2) CHECK (price > 0),
    size_of_package VARCHAR2(255)
);

CREATE TABLE Repository (
    repository_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_name VARCHAR2(255) NOT NULL,
    capacity INT CHECK (capacity >= 0)
);

CREATE TABLE Sales (
    sale_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sell_timestamp TIMESTAMP NOT NULL,
    pharmacist_name VARCHAR2(255) NOT NULL,
    payment_method VARCHAR2(32),
    CHECK (payment_method IN ('Cash', 'Credit Card', 'Mobile Payment'))
);

CREATE TABLE Sale_Items (
    sale_id INT REFERENCES Sales(sale_id) ON DELETE CASCADE,
    product_id INT REFERENCES Products(product_id),
    amount INT NOT NULL,
    CONSTRAINT chk_sale_amount CHECK (amount > 0),
    PRIMARY KEY (sale_id, product_id)
);

CREATE TABLE Health_insurance_company (
    number_of_company VARCHAR2(8) PRIMARY KEY,
    company_name VARCHAR2(255) NOT NULL,
    CHECK (REGEXP_LIKE(number_of_company, '^[0-9]{8}$'))
);

CREATE TABLE Statements (
    statement_id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_from DATE NOT NULL,
    transaction_to DATE NOT NULL,
    date_of_export DATE NOT NULL,
    sale_id INT REFERENCES Sales(sale_id) ON DELETE CASCADE,
    number_of_company VARCHAR2(8) REFERENCES Health_insurance_company(number_of_company)
);

CREATE TABLE Effect (
    effect_name VARCHAR2(255) PRIMARY KEY,
    effect_type VARCHAR2(255) NOT NULL,
    effect_description VARCHAR2(1024)
);

--inheritance
-- We decided to use Table for Supertype + Tables for Subtypes with Primary keys of Supertype,
-- because of the simplicity of the database and the fact that we do not have many subtypes.
-- We also wanted to avoid the complexity of using a single table for all products
-- This offers good scalability because we can add new categories (like "Electronics")
-- by simply creating a new table without modifying the existing database structure.
-- We think that for example for inventory management it is easier to have separate tables for medicines and additional goods,
-- because they have different attributes and we can avoid having many NULL values in a single table.

CREATE TABLE Medicine (
    medicine_id INT PRIMARY KEY REFERENCES Products(product_id),
    method_of_disbursement VARCHAR2(255) NOT NULL, -- if it is prescription or not
    effect_name VARCHAR2(255) REFERENCES Effect(effect_name),
    CHECK (method_of_disbursement IN ('Prescription', 'Free Sale'))
);

--inheritance
CREATE TABLE Additional_goods (
    product_id INT PRIMARY KEY REFERENCES Products(product_id),
    category_of_goods VARCHAR2(255) NOT NULL
);

CREATE TABLE Contribute_to (
    number_of_company VARCHAR2(8) REFERENCES Health_insurance_company(number_of_company),
    medicine_id INT REFERENCES Medicine(Medicine_id),
    contribution_amount NUMBER(8, 2) NOT NULL,
    available_from DATE NOT NULL,
    available_to DATE NOT NULL,
    CHECK (available_from <= available_to),
    CONSTRAINT chk_contribution CHECK (contribution_amount >= 0),
    PRIMARY KEY (number_of_company, medicine_id)
);

CREATE TABLE Repo_contains (
    product_id INT REFERENCES Products(product_id),
    repository_id INT REFERENCES Repository(repository_id),
    amount_on_repository INT NOT NULL,
    date_of_supply DATE,
    CONSTRAINT chk_amount CHECK (amount_on_repository >= 0),
    PRIMARY KEY (product_id, repository_id)
);

